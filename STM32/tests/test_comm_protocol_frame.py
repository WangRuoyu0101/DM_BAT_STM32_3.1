from pathlib import Path
import unittest


ROOT = Path(__file__).resolve().parents[1]


class CommProtocolFrameTests(unittest.TestCase):
    def read(self, relative_path):
        return (ROOT / relative_path).read_text(encoding="utf-8")

    def test_protocol_module_defines_binary_frame_layout(self):
        header = self.read("Core/Inc/app_comm_protocol.h")
        source = self.read("Core/Src/app_comm_protocol.c")
        makefile = self.read("Makefile")

        self.assertIn("#define APP_COMM_FRAME_HEADER0 0xAAU", header)
        self.assertIn("#define APP_COMM_FRAME_HEADER1 0x55U", header)
        self.assertIn("#define APP_COMM_CRC8_POLY 0x07U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_STATUS_QUERY 0x01U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_GPIO_CONTROL_REQUEST 0x02U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_GPIO_STATUS_QUERY 0x03U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_ULTRASONIC_QUERY 0x04U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_STATUS_RESPONSE 0x81U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_GPIO_CONTROL_RESPONSE 0x82U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_GPIO_STATUS_RESPONSE 0x83U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_ULTRASONIC_RESPONSE 0x84U", header)
        self.assertIn("#define APP_COMM_FRAME_ID_ERROR_RESPONSE 0xE1U", header)
        self.assertIn("#define APP_COMM_ERROR_CODE_CMD 0x01U", header)
        self.assertIn("#define APP_COMM_ERROR_CODE_CHECKSUM 0x02U", header)
        self.assertIn("#define APP_COMM_ERROR_CODE_LENGTH 0x03U", header)
        self.assertIn("#define APP_COMM_GPIO_CHANNEL_FLASH_CTR 0x01U", header)
        self.assertIn("#define APP_COMM_GPIO_CHANNEL_LED 0x02U", header)
        self.assertIn("#define APP_COMM_GPIO_CHANNEL_BEE 0x03U", header)
        self.assertIn("#define APP_COMM_GPIO_CHANNEL_MOTOR 0x04U", header)
        self.assertIn("#define APP_COMM_GPIO_CHANNEL_FLASH 0x05U", header)
        self.assertIn("#define APP_COMM_GPIO_CHANNEL_SOUND 0x06U", header)
        self.assertIn("#define APP_COMM_GPIO_LEVEL_LOW 0x00U", header)
        self.assertIn("#define APP_COMM_GPIO_LEVEL_HIGH 0x01U", header)
        self.assertIn("#define APP_COMM_CONTROL_RESULT_OK 0x00U", header)
        self.assertIn("#define APP_COMM_CONTROL_RESULT_INVALID_CHANNEL 0x01U", header)
        self.assertIn("#define APP_COMM_CONTROL_RESULT_INVALID_LEVEL 0x02U", header)
        self.assertIn("#define APP_COMM_CONTROL_RESULT_LENGTH_ERROR 0x03U", header)
        self.assertIn("#define APP_COMM_FRAME_OVERHEAD 5U", header)
        self.assertIn("#define APP_COMM_MAX_PAYLOAD_SIZE 250U", header)
        self.assertIn("typedef struct", header)
        self.assertIn("App_CommFrame", header)
        self.assertIn("App_CommStatusQuery", header)
        self.assertIn("App_CommGpioControl", header)
        self.assertIn("App_CommGpioStatusQuery", header)
        self.assertIn("App_CommUltrasonicQuery", header)
        self.assertIn("App_CommParser", header)
        self.assertIn("App_CommProtocol_Encode", header)
        self.assertIn("App_CommProtocol_ParseByte", header)
        self.assertIn("App_CommProtocol_DecodeStatusQuery", header)
        self.assertIn("App_CommProtocol_DecodeGpioControlRequest", header)
        self.assertIn("App_CommProtocol_DecodeGpioStatusQuery", header)
        self.assertIn("App_CommProtocol_DecodeUltrasonicQuery", header)
        self.assertIn('#include "app_comm_protocol.h"', source)
        self.assertIn("Core/Src/app_comm_protocol.c", makefile)

    def test_protocol_checksum_and_parser_are_implemented(self):
        source = self.read("Core/Src/app_comm_protocol.c")

        self.assertIn("crc ^= byte;", source)
        self.assertIn("APP_COMM_CRC8_POLY", source)
        self.assertIn("checksum = App_CommProtocol_Crc8Byte(checksum, frame_id);", source)
        self.assertIn("checksum = App_CommProtocol_Crc8Byte(checksum, length);", source)
        self.assertIn("checksum = App_CommProtocol_Crc8Byte(checksum, data[index]);", source)
        self.assertIn("APP_COMM_PARSE_WAIT_HEADER0", source)
        self.assertIn("APP_COMM_PARSE_WAIT_HEADER1", source)
        self.assertIn("APP_COMM_PARSE_FRAME_ID", source)
        self.assertIn("APP_COMM_PARSE_LENGTH", source)
        self.assertIn("APP_COMM_PARSE_DATA", source)
        self.assertIn("APP_COMM_PARSE_CHECKSUM", source)
        self.assertIn("APP_COMM_PARSE_FRAME_READY", source)
        self.assertIn("APP_COMM_PARSE_CHECKSUM_ERROR", source)
        self.assertIn("frame->frame_id != APP_COMM_FRAME_ID_STATUS_QUERY", source)
        self.assertIn("query->seq = frame->data[0];", source)
        self.assertIn("frame->frame_id != APP_COMM_FRAME_ID_GPIO_CONTROL_REQUEST", source)
        self.assertIn("control->seq = frame->data[0];", source)
        self.assertIn("control->channel_id = frame->data[1];", source)
        self.assertIn("control->level = frame->data[2];", source)
        self.assertIn("frame->frame_id != APP_COMM_FRAME_ID_GPIO_STATUS_QUERY", source)
        self.assertIn("query->seq = frame->data[0];", source)
        self.assertIn("frame->frame_id != APP_COMM_FRAME_ID_ULTRASONIC_QUERY", source)
        self.assertIn("App_CommProtocol_DecodeUltrasonicQuery", source)
        self.assertNotIn('"STATUS?"', source)
